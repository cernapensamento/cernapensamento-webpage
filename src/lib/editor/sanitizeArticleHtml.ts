/**
 * Sanitizes article HTML content using the canonical whitelist for Cerna Pensamento,
 * stripping scripts, javascript: URIs, onerror handlers, and untrusted embeds.
 */
export function sanitizeArticleHtml(html: string): string {
  if (!html) return '';
  return sanitizeHtml(html, ARTICLE_SANITIZER_CONFIG);
}
